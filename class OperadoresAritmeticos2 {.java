class OperadoresAritmeticos2 {
    public static void main(String[] args) {
        double numero1 = 7.0;
        double numero2 = 5.0;

        System.out.println("Operaciones con \"numero1\" y \"numero2\":");
        System.out.println(numero1 + numero2);  // Suma
        System.out.println(numero1 - numero2);  // Resta
        System.out.println(numero1 * numero2);  // Multiplicación
        System.out.println(numero1 / numero2);  // División con decimales
        System.out.println(numero1 % numero2);  // Módulo
    } // Fin del método main
} // Fin de la clase OperadoresAritmeticos 2